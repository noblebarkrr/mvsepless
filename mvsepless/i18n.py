# Функция для получения перевода
def _i18n(key: str, **kwargs) -> str:
    """
    Получить перевод для текущего языка с возможностью форматирования
    
    Args:
        key: Ключ перевода
        **kwargs: Аргументы для форматирования строки
    
    Returns:
        Переведенная строка
    """
    translation = TRANSLATIONS[CURRENT_LANGUAGE].get(key, key)
    if kwargs:
        try:
            return translation.format(**kwargs)
        except (KeyError, IndexError) as e:
            # Если ключ форматирования не найден, возвращаем как есть
            return translation
    return translation

# Функция для смены языка
def set_language(lang: Language) -> None:
    """
    Установить язык
    
    Args:
        lang: Код языка ("ru" или "en")
    """
    global CURRENT_LANGUAGE
    if lang in TRANSLATIONS:
        CURRENT_LANGUAGE = lang
    else:
        CURRENT_LANGUAGE = "en"

# Вспомогательные функции для часто используемых переводов
def ngettext(singular: str, plural: str, count: int) -> str:
    """
    Выбор правильной формы множественного числа
    
    Args:
        singular: Ключ для единственного числа
        plural: Ключ для множественного числа
        count: Количество
    
    Returns:
        Перевод с правильной формой
    """
    if CURRENT_LANGUAGE == "ru":
        # Русские правила множественного числа
        if count % 10 == 1 and count % 100 != 11:
            return _i18n(singular, count=count)
        elif 2 <= count % 10 <= 4 and (count % 100 < 10 or count % 100 >= 20):
            return _i18n(plural + "_2", count=count)
        else:
            return _i18n(plural + "_5", count=count)
    else:
        # Английские правила

        return _i18n(singular if count == 1 else plural, count=count)
